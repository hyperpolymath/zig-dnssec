# Cross-checks zig-dnssec's verdicts against Unbound and ldns (drill -S) on
# the fixed zone set, and writes REPORT.adoc. Every disagreement is listed.
#
#   ./make-zones.sh        # once (or after the signatures expire)
#   ./servers.sh start
#   ./run.sh               # writes REPORT.adoc and work/results.tsv
#   ./servers.sh stop
#
# Our stub talks DoH (HTTP/1.1 via haproxy -> Unbound) with CD=1 and does its
# own validation; Unbound's verdict comes from a normal query (AD bit /
# SERVFAIL); ldns's from `drill -S` (signature chase) through the same Unbound.
set -uo pipefail
cd "$(dirname "$0")"
W="$PWD/work"
BIN="$PWD/../../zig-out/bin/dnssec-stub"
[[ -x "$BIN" ]] || { echo "build first: zig build" >&2; exit 2; }
mkdir -p "$W/traces"
grep -v '^;' zones/root.anchor > "$W/root.anchor.drill"

LEAVES=(rsasha256 rsasha512 rsasha1 nsec3sha1 ecdsa256 ecdsa384 ed25519 ed448
        expired notyet wrongkey nodnskey tampered badsig highiter dname island dssha1 insecure)

queries() {
  printf '%s\n' ". SOA" ". DNSKEY" "test. SOA" "test. DNSKEY" "test. DS" "nx.test. A" "nxtld. A"
  for l in "${LEAVES[@]}"; do
    z="$l.test."
    printf '%s\n' "www.$z A" "www.$z AAAA" "$z SOA" "$z DNSKEY" "$z DS" "$z MX" \
      "nx.$z A" "www.$z MX" "alias.$z A" "foo.wild.$z A" "foo.wild.$z AAAA" "ent.$z A" "txt.$z TXT"
  done
  printf '%s\n' "www.unsigned.ecdsa256.test. A" "unsigned.ecdsa256.test. DS" \
    "www.redir.dname.test. A" "redir.dname.test. DNAME" "nx.redir.dname.test. A" \
    "www.rsasha256.test. DS" "www.rsasha512.test. DS" "nx.rsasha256.test. DS" "alias.rsasha256.test. CNAME"
}

unbound_verdict() { # name type
  local out status flags
  out=$(dig +dnssec +time=5 +tries=1 @127.0.0.1 -p 5301 "$1" "$2" 2>&1)
  status=$(sed -n 's/.*status: \([A-Z]*\),.*/\1/p' <<<"$out" | head -1)
  flags=$(sed -n 's/^;; flags: \([a-z ]*\);.*/\1/p' <<<"$out" | head -1)
  case "$status" in
    SERVFAIL) echo "bogus" ;;
    NOERROR|NXDOMAIN) if [[ " $flags " == *" ad "* ]]; then echo "secure"; else echo "insecure"; fi ;;
    *) echo "error:$status" ;;
  esac
}

ldns_verdict() { # name type
  local out
  out=$(timeout 30 drill -S -k "$W/root.anchor.drill" @127.0.0.1 -p 5301 "$1" "$2" 2>&1)
  if grep -q 'Chase successful' <<<"$out"; then
    if grep -q 'Existence denied or verifiably insecure' <<<"$out"; then echo "denied-or-insecure"; else echo "secure"; fi
  else
    local why; why=$(sed -n 's/.*first error was: //p' <<<"$out" | head -1)
    echo "failed:${why:-unknown}" | tr ' ' '_'
  fi
}

# Is an ldns outcome compatible with our verdict? drill -S cannot prove
# insecurity and merges "secure denial" with "insecure", so map coarsely.
ldns_compatible() { # ours ldns rcode
  local ours=$1 l=$2
  case "$ours:$l" in
    secure:secure|secure:denied-or-insecure) return 0 ;;
    insecure:denied-or-insecure|insecure:failed:No_DNSSEC_public_key\(s\)) return 0 ;;
    bogus:failed:*) return 0 ;;
  esac
  return 1
}

ours_verdict() { # policy-flags name type -> "verdict reason"
  local flags=$1 n=$2 t=$3 out v r
  local trace="$W/traces/$(tr '/' '_' <<<"$n")$t.trace"
  : > "$trace"
  # shellcheck disable=SC2086
  out=$("$BIN" --doh https://localhost:8444/dns-query --ca "$W/tls/ca.pem" \
        --anchors zones/root.anchor --record "$trace" $flags "$n" "$t" 2>&1 | head -1)
  v=$(sed -n 's/^verdict=\([a-z]*\).*/\1/p' <<<"$out")
  r=$(sed -n 's/.* reason=\([^ ]*\).*/\1/p' <<<"$out")
  echo "${v:-error} ${r:--}"
}

: > "$W/results.tsv"
total=0; dis_ub=0; dis_ub_rfc=0; dis_ldns=0
while read -r name type; do
  total=$((total + 1))
  read -r ov orr < <(ours_verdict "" "$name" "$type")
  read -r rv rr < <(ours_verdict "--unsupported-insecure --iterations-insecure" "$name" "$type")
  ub=$(unbound_verdict "$name" "$type")
  ld=$(ldns_verdict "$name" "$type")
  [[ "$ov" != "$ub" ]] && dis_ub=$((dis_ub + 1))
  [[ "$rv" != "$ub" ]] && dis_ub_rfc=$((dis_ub_rfc + 1))
  ldns_compatible "$ov" "$ld" || dis_ldns=$((dis_ldns + 1))
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$name" "$type" "$ov" "$orr" "$rv" "$rr" "$ub" "$ld" >> "$W/results.tsv"
done < <(queries)

tbl() { echo "[cols=\"$1\",options=\"header\"]"; echo "|==="; }
{
  echo "// SPDX-License-Identifier: CC-BY-SA-4.0"
  echo "// SPDX-FileCopyrightText: 2026 Jonathan D.A. Jewell"
  echo "// GENERATED by tests/crosscheck/run.sh — do not edit by hand."
  echo "= Cross-check report: zig-dnssec vs Unbound and ldns"
  echo ":toc:"
  echo
  echo "Generated $(date -u +%Y-%m-%dT%H:%M:%SZ) by \`tests/crosscheck/run.sh\`."
  echo
  echo "* zig-dnssec: $(git -C ../.. rev-parse --short HEAD 2>/dev/null || echo unknown) (Zig $(zig version))"
  echo "* Unbound: $(unbound -V 2>&1 | head -1)"
  echo "* ldns: $(drill -v 2>&1 | head -1)"
  echo "* NSD: $(nsd -v 2>&1 | head -1)"
  echo
  echo "Queries: $total. Our verdict is produced over DoH (HTTP/1.1 via haproxy to Unbound's"
  echo "HTTP/2 listener) with CD=1 and our own validation; Unbound's from its own validation"
  echo "(AD bit / SERVFAIL); ldns's from \`drill -S\` chasing signatures through the same Unbound."
  echo
  tbl "3,1"
  echo "| Comparison | Disagreements"
  echo "| ours (default policy) vs Unbound | $dis_ub"
  echo "| ours (RFC-permissive policy: unsupported algorithms and excess NSEC3 iterations reported insecure) vs Unbound | $dis_ub_rfc"
  echo "| ours (default) vs ldns, after mapping ldns's coarser outcomes | $dis_ldns"
  echo "|==="
  echo
  echo "== Every disagreement with Unbound (default policy)"
  echo
  tbl "3,1,2,1,2"
  echo "| Query | Ours | Reason | Unbound | ldns"
  awk -F'\t' '$3 != $7 { printf "| `%s %s` | %s | %s | %s | %s\n", $1, $2, $3, $4, $7, $8 }' "$W/results.tsv"
  echo "|==="
  echo
  echo "== Every disagreement with Unbound (RFC-permissive policy)"
  echo
  tbl "3,1,2,1"
  echo "| Query | Ours | Reason | Unbound"
  awk -F'\t' '$5 != $7 { printf "| `%s %s` | %s | %s | %s\n", $1, $2, $5, $6, $7 }' "$W/results.tsv"
  echo "|==="
  echo
  echo "== Every ldns outcome not compatible with our verdict"
  echo
  tbl "3,1,2,3"
  echo "| Query | Ours | Reason | ldns (drill -S)"
  while IFS=$'\t' read -r n t ov orr rv rr ub ld; do
    ldns_compatible "$ov" "$ld" || echo "| \`$n $t\` | $ov | $orr | $ld"
  done < "$W/results.tsv"
  echo "|==="
  echo
  echo "== Zone-level check with ldns-verify-zone"
  echo
  tbl "2,3"
  echo "| Zone file | Result"
  for f in zones/*.signed; do
    echo "| $(basename "$f") | $(ldns-verify-zone "$f" 2>&1 | tail -1)"
  done
  echo "|==="
  echo
  echo "== All results"
  echo
  tbl "3,1,2,1,2,1,2"
  echo "| Query | Ours | Reason | Ours (permissive) | Reason | Unbound | ldns"
  awk -F'\t' '{ printf "| `%s %s` | %s | %s | %s | %s | %s | %s\n", $1, $2, $3, $4, $5, $6, $7, $8 }' "$W/results.tsv"
  echo "|==="
} > REPORT.adoc

echo "queries=$total disagreements: unbound=$dis_ub unbound(permissive)=$dis_ub_rfc ldns=$dis_ldns"
